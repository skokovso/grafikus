def _parse_md_blocks(text: str):
    """Markdown → список блоков (kind, payload).

    kinds: title, h2, h3, h4, p, bullet, code, table.
    Заголовки возвращаются БЕЗ номеров — нумерацию добавляет рендер.
    """
    blocks, buf, fence, table = [], [], False, []
    for raw in text.splitlines():
        line = raw.rstrip()
        if line.startswith("```"):
            if fence:
                blocks.append(("code", buf))
                buf = []
            fence = not fence
            continue
        if fence:
            buf.append(line)
            continue
        if line.startswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if not all(set(c) <= set("-: ") for c in cells if c):
                table.append(cells)
            continue
        if table:
            blocks.append(("table", table))
            table = []
        if not line.strip():
            continue
        if line.startswith("# "):
            blocks.append(("title", line[2:].strip()))
        elif line.startswith("## "):
            blocks.append(("h2", line[3:].strip()))
        elif line.startswith("### "):
            blocks.append(("h3", line[4:].strip()))
        elif line.startswith("#### "):
            blocks.append(("h4", line[5:].strip()))
        elif line.startswith("- "):
            blocks.append(("bullet", line[2:].strip()))
        else:
            blocks.append(("p", line.strip()))
    if table:
        blocks.append(("table", table))
    return blocks


def _find_logo() -> Path | None:
    """Логотип по цепочке: assets/project_logo.png → .ico → logo.png → icon.ico."""
    candidates = [
        ASSETS_DIR / "project_logo.png",
        ASSETS_DIR / "project_logo.ico",
        ASSETS_DIR / "logo.png",
        BASE_DIR / "icon.ico",
    ]
    for p in candidates:
        if p.exists():
            return p
    return None


def render_md_to_docx(md_path: Path, docx_path: Path) -> bool:
    """Рендерит markdown в docx с логотипом и авто-нумерацией заголовков."""
    try:
        from docx import Document
        from docx.shared import Pt, Cm
        from docx.enum.text import WD_ALIGN_PARAGRAPH
    except ImportError:
        print("⚠️ python-docx не установлен — пропускаю docx")
        return False

    try:
        text = md_path.read_text(encoding="utf-8")
        blocks = _parse_md_blocks(text)

        doc = Document()
        style = doc.styles["Normal"]
        style.font.name = "Times New Roman"
        style.font.size = Pt(12)
        for sec in doc.sections:
            sec.left_margin = Cm(2.5)
            sec.right_margin = Cm(1.5)
            sec.top_margin = Cm(2.0)
            sec.bottom_margin = Cm(2.0)

        logo = _find_logo()
        if logo:
            try:
                doc.add_picture(str(logo), width=Cm(5))
                doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
            except Exception as e:
                print(f"⚠️ Логотип не вставлен: {e}")

        n2 = n3 = n4 = 0

        for kind, payload in blocks:
            if kind == "title":
                p = doc.add_paragraph()
                p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                r = p.add_run(payload)
                r.bold = True
                r.font.size = Pt(18)
            elif kind == "h2":
                n2 += 1
                n3 = n4 = 0
                p = doc.add_paragraph()
                p.paragraph_format.space_before = Pt(14)
                p.paragraph_format.space_after = Pt(6)
                r = p.add_run(f"{n2}. {payload}")
                r.bold = True
                r.font.size = Pt(15)
            elif kind == "h3":
                n3 += 1
                n4 = 0
                p = doc.add_paragraph()
                p.paragraph_format.space_before = Pt(10)
                p.paragraph_format.space_after = Pt(4)
                r = p.add_run(f"{n2}.{n3}. {payload}")
                r.bold = True
                r.font.size = Pt(13)
            elif kind == "h4":
                n4 += 1
                p = doc.add_paragraph()
                p.paragraph_format.space_before = Pt(8)
                p.paragraph_format.space_after = Pt(4)
                r = p.add_run(f"{n2}.{n3}.{n4}. {payload}")
                r.bold = True
                r.font.size = Pt(12)
            elif kind == "p":
                clean = payload.replace("`", "")
                doc.add_paragraph(clean)
            elif kind == "bullet":
                clean = payload.replace("`", "")
                doc.add_paragraph(clean, style="List Bullet")
            elif kind == "code":
                for ln in payload:
                    p = doc.add_paragraph()
                    r = p.add_run(ln)
                    r.font.name = "Courier New"
                    r.font.size = Pt(10)
            elif kind == "table":
                rows = payload
                if rows:
                    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
                    t.style = "Table Grid"
                    for i, row in enumerate(rows):
                        for j, cell in enumerate(row):
                            if j < len(t.rows[i].cells):
                                t.rows[i].cells[j].text = cell.replace("`", "")
                    doc.add_paragraph()

        doc.save(str(docx_path))
        return True
    except Exception as e:
        print(f"❌ Ошибка рендера docx: {e}")
        return False


def render_md_to_pdf(md_path: Path, pdf_path: Path) -> bool:
    """PDF: сначала через Word (docx2pdf), если не получилось — fpdf2."""
    docx_tmp = pdf_path.with_suffix(".docx")
    if not render_md_to_docx(md_path, docx_tmp):
        return _fallback_pdf(md_path, pdf_path)

    try:
        from docx2pdf import convert
        convert(str(docx_tmp), str(pdf_path))
        print(f"✅ PDF (Word): {pdf_path}")
        return True
    except ImportError:
        print("⚠️ docx2pdf не установлен — падаю на fpdf2")
    except Exception as e:
        print(f"⚠️ Word не сработал ({e}) — падаю на fpdf2")

    return _fallback_pdf(md_path, pdf_path)


def _fallback_pdf(md_path: Path, pdf_path: Path) -> bool:
    """Резервный путь: fpdf2 через manuals_to_pdf.render."""
    try:
        sys.path.insert(0, str(BASE_DIR / "service" / "docs"))
        from manuals_to_pdf import render as _fpdf_render
        _fpdf_render(md_path, pdf_path)
        return True
    except Exception as e:
        print(f"❌ fpdf2-рендер не удался: {e}")
        return False


