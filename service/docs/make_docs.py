def main() -> None:
    only_missing = "--only-missing" in sys.argv
    force = "--force" in sys.argv
    
    MANUALS_DIR.mkdir(parents=True, exist_ok=True)
    created = skipped = 0
    
    for name, lines in DOCS.items():
        # ИСПРАВЛЕНИЕ: корректно определяем путь, чтобы не дублировать папку manuals
        if name.startswith("manuals/"):
            clean_name = name.replace("manuals/", "", 1)
            path = MANUALS_DIR / clean_name
        else:
            path = BASE_DIR / name
            
        existed = path.exists()
        
        if existed and only_missing and not force:
            print(f"⏭️ Пропущен (уже есть): {name}")
            skipped += 1
            continue
            
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        
        status = "переписан" if existed else "создан"
        print(f"✅ {status}: {path.relative_to(BASE_DIR)} ({len(lines)} строк)")
        created += 1
        
    print("\n" + "="*60)
    print(f"Готово: создано/переписано {created}, пропущено {skipped}.")
    print("Тексты правятся ТОЛЬКО в словаре DOCS этого файла.")
    print("Бережный режим (не трогать существующее): --only-missing")
    print("Принудительная перезапись: --force")
    print("Для сборки PDF руководств: python service/docs/manuals_to_pdf.py")

if __name__ == "__main__":
    main()